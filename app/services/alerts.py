def generate_alerts_for_device(db: Session, device: Device, failed_policy_ids: List[str]) -> List[Alert]:
    """Generates and deduplicates alerts for a given device based on posture and risk score."""
    new_alerts = []
    
    # Check existing open/acknowledged/investigating alerts to prevent spamming
    existing_open = db.query(Alert).filter(
        Alert.device_id == device.device_id,
        Alert.status.in_(["Open", "Acknowledged", "Investigating"])
    ).all()
    existing_titles = {a.title for a in existing_open}

    # Policy-specific alert generation
    for pol_id in failed_policy_ids:
        if pol_id in ALERT_TEMPLATES:
            template = ALERT_TEMPLATES[pol_id]
            if template["title"] not in existing_titles:
                alert_id = f"ALT-{str(uuid.uuid4())[:8].upper()}"
                alert = Alert(
                    id=alert_id,
                    device_id=device.device_id,
                    title=template["title"],
                    severity=template["severity"],
                    category=template["category"],
                    description=template["desc_fn"](device),
                    status="Open",
                    mitre_technique=template["mitre_technique"],
                    assigned_to="SOC Analyst",
                    notes="Auto-generated by SentinelEdge Threat Engine.",
                    created_at=datetime.datetime.utcnow()
                )
                db.add(alert)
                new_alerts.append(alert)
                existing_titles.add(template["title"])

    # High / Critical overall risk alert
    if device.risk_score >= 75.0 and ALERT_TEMPLATES["RISK_CRITICAL"]["title"] not in existing_titles:
        template = ALERT_TEMPLATES["RISK_CRITICAL"]
        alert_id = f"ALT-{str(uuid.uuid4())[:8].upper()}"
        alert = Alert(
            id=alert_id,
            device_id=device.device_id,
            title=template["title"],
            severity=template["severity"],
            category=template["category"],
            description=template["desc_fn"](device),
            status="Open",
            mitre_technique=template["mitre_technique"],
            assigned_to="SOC Lead",
            notes="Requires immediate administrator remediation.",
            created_at=datetime.datetime.utcnow()
        )
        db.add(alert)
        new_alerts.append(alert)

    return new_alerts
